[CmdletBinding()]
param(
    [ValidateSet('Debug', 'Release')][string]$Configuration = 'Release',
    [ValidateSet('win-x64', 'win-arm64')][string]$Runtime = 'win-x64',
    [switch]$SelfContained
)
$ErrorActionPreference = 'Stop'
$projectRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$appOutput = [IO.Path]::GetFullPath((Join-Path $projectRoot 'app'))
$distOutput = Join-Path $projectRoot 'dist'
# app/ is exclusively generated output. Never clear an arbitrary supplied path.
if ($appOutput -ne [IO.Path]::Combine($projectRoot, 'app')) { throw 'Unexpected output directory.' }
if (Test-Path -LiteralPath $appOutput) {
    if (-not (Test-Path -LiteralPath (Join-Path $appOutput '.structure-editor-output'))) {
        throw 'app/ is not marked as generated output. Move its contents before building.'
    }
    Remove-Item -LiteralPath $appOutput -Recurse -Force
}
# app/ is a generated executable, not a second copy of the source library.
# The repository keeps one editable structures/ and docs/ at its root.
# Only the downloadable standalone archive needs its own portable resources.
New-Item -ItemType Directory -Path $appOutput -Force | Out-Null
Set-Content -LiteralPath (Join-Path $appOutput '.structure-editor-output') -Value 'Generated by scripts/build.ps1'
$contained = if ($SelfContained) { 'true' } else { 'false' }
dotnet publish (Join-Path $projectRoot 'src/StructureEditor/StructureEditor.csproj') -c $Configuration -r $Runtime --self-contained $contained -o $appOutput -p:DebugType=None -p:DebugSymbols=false --nologo
if ($LASTEXITCODE -ne 0) { throw 'dotnet publish failed.' }
if ($SelfContained) {
    Copy-Item -LiteralPath (Join-Path $projectRoot 'docs/使用说明.md'), (Join-Path $projectRoot 'LICENSE') -Destination $appOutput
    if (Test-Path -LiteralPath (Join-Path $projectRoot 'structures')) {
        Copy-Item -LiteralPath (Join-Path $projectRoot 'structures') -Destination $appOutput -Recurse
    }
}
New-Item -ItemType Directory -Path $distOutput -Force | Out-Null
$projectXml = [xml](Get-Content -LiteralPath (Join-Path $projectRoot 'src/StructureEditor/StructureEditor.csproj') -Raw)
$version = $projectXml.Project.PropertyGroup.Version
$flavor = if ($SelfContained) { 'standalone' } else { 'desktop-runtime' }
$archive = Join-Path $distOutput "StructureEditor-$version-$Runtime-$flavor.zip"
Compress-Archive -Path (Join-Path $appOutput '*') -DestinationPath $archive -Force
Write-Output "Application: $appOutput"
Write-Output "Package: $archive"
